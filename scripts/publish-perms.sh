#!/bin/sh
# Права для того, что раздаёт Caddy. Подключается через `.` из скриптов выкладки.
#
# Зачем отдельный файл. Caddy работает не нашим пользователем, а umask бывает
# 077: `mkdir -p` создаёт родительские каталоги 0700, файлы копируются 0600, и
# сайт отдаёт 403 на артефакт — при том что `ls` внутри выглядит нормально, а
# лог сборки чист. Эта грабля всплывала дважды (установщик десктопа, релиз
# веб-клиента) и оба раза искалась заново, поэтому правило теперь одно.
#
# Использование: publish_perms <корень, который уже существует> <путь до листа>
#
# Первый аргумент — граница: выше него права не трогаем (это каталоги сайта,
# их настраивает человек). Второй — лист, до которого надо дотянуть 0755.

# Префикс `_pub_`/`_root`… — переменные не должны затирать окружение
# вызывающего: файл подключается через `.` из release-скриптов, и их
# собственные `_dir`/`_perm` после вызова стали бы нашими. Тело — в подоболочке
# `( … )`: в POSIX sh нет `local`, а так все переменные остаются внутри.
publish_perms() (
    _root="$1"
    _leaf="$2"
    [ -d "$_root" ] || return 1
    [ -d "$_leaf" ] || return 1
    # Граница сравнивается канонически: с завершающим слэшем, относительным
    # путём или `..` в аргументе сырое сравнение никогда не совпало бы с
    # `dirname`-цепочкой, цикл не остановился бы на границе и сделал бы
    # `chmod 0755` на /var/www и /var. `pwd -P` разрешает и симлинки.
    _root_p="$(cd "$_root" 2>/dev/null && pwd -P)" || return 1
    _leaf_p="$(cd "$_leaf" 2>/dev/null && pwd -P)" || return 1
    [ -n "$_root_p" ] && [ -n "$_leaf_p" ] || return 1
    # И что лист вообще лежит под корнем: иначе граница бессмысленна.
    case "$_leaf_p" in
        "$_root_p" | "$_root_p"/*) : ;;
        *) return 1 ;;
    esac
    _dir="$_leaf_p"
    while [ "$_dir" != "$_root_p" ] && [ "$_dir" != "/" ] && [ "$_dir" != "." ]; do
        chmod 0755 "$_dir" 2>/dev/null || return 1
        _dir="$(dirname "$_dir")"
    done
    # Файлы: каталог версии неизменяем, поэтому рекурсивно, а не только лист.
    # `-type d`/`-type f` — только каталоги и обычные файлы (симлинки не трогаем),
    # а x-бит у файлов не снимаем: нынешний лист — tar.gz и .sha256, но
    # `chmod 0644` по всем файлам убил бы исполняемое, если оно там окажется.
    find "$_leaf" -type d -exec chmod 0755 {} + 2>/dev/null || true
    find "$_leaf" -type f -perm -u+x -exec chmod 0755 {} + 2>/dev/null || true
    find "$_leaf" -type f ! -perm -u+x -exec chmod 0644 {} + 2>/dev/null || true
    return 0
)

# Проверка, что файл реально доступен анонимному читателю: повторяет решение
# Caddy (другие uid/gid, только «всем»). Права проверяются по факту, а не по
# вере в chmod: символические ссылки и ACL дают другие ответы.
# Подоболочка — по той же причине, что и у publish_perms.
publish_readable() (
    _path="$1"
    [ -f "$_path" ] || return 1
    # r для others на всех родителях и на самом файле.
    _dir="$(dirname "$_path")"
    while [ "$_dir" != "/" ] && [ "$_dir" != "." ]; do
        _perm="$(stat -c '%a' "$_dir" 2>/dev/null || echo 0)"
        # Нужен бит x у others, а не любая из 5/6/7: 6 = rw- — в каталог не
        # войти, Caddy всё равно отдаст 403. Годятся 1, 3, 5, 7.
        case "$_perm" in
            *[1357]) : ;;
            *) return 1 ;;
        esac
        _dir="$(dirname "$_dir")"
    done
    _perm="$(stat -c '%a' "$_path" 2>/dev/null || echo 0)"
    case "$_perm" in
        *[4-7]) return 0 ;;
        *) return 1 ;;
    esac
)
