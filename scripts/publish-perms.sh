#!/bin/sh
# Права для того, что раздаёт Caddy. Подключается через `.` из скриптов выкладки.
#
# Зачем отдельный файл. Caddy работает не нашим пользователем, а umask бывает
# 077: `mkdir -p` создаёт родительские каталоги 0700, файлы копируются 0600, и
# сайт отдаёт 403 на артефакт — при том что `ls` внутри выглядит нормально, а
# лог сборки чист. Эта грабля всплывала дважды (установщик десктопа, релиз
# веб-клиента) и оба раза искалась заново, поэтому правило теперь одно.
#
# Использование: publish_perms <корень, который уже существует> <путь до листа>
#
# Первый аргумент — граница: выше него права не трогаем (это каталоги сайта,
# их настраивает человек). Второй — лист, до которого надо дотянуть 0755.

publish_perms() {
    _root="$1"
    _leaf="$2"
    [ -d "$_root" ] || return 1
    _dir="$_leaf"
    while [ "$_dir" != "$_root" ] && [ "$_dir" != "/" ] && [ "$_dir" != "." ]; do
        chmod 0755 "$_dir" 2>/dev/null || return 1
        _dir="$(dirname "$_dir")"
    done
    # Файлы: каталог версии неизменяем, поэтому рекурсивно, а не только лист.
    find "$_leaf" -type d -exec chmod 0755 {} + 2>/dev/null || true
    find "$_leaf" -type f -exec chmod 0644 {} + 2>/dev/null || true
    return 0
}

# Проверка, что файл реально доступен анонимному читателю: повторяет решение
# Caddy (другие uid/gid, только «всем»). Права проверяются по факту, а не по
# вере в chmod: символические ссылки и ACL дают другие ответы.
publish_readable() {
    _path="$1"
    [ -f "$_path" ] || return 1
    # r для others на всех родителях и на самом файле.
    _dir="$(dirname "$_path")"
    while [ "$_dir" != "/" ] && [ "$_dir" != "." ]; do
        _perm="$(stat -c '%a' "$_dir" 2>/dev/null || echo 0)"
        case "$_perm" in
            *[5-7]) : ;;
            *) return 1 ;;
        esac
        _dir="$(dirname "$_dir")"
    done
    _perm="$(stat -c '%a' "$_path" 2>/dev/null || echo 0)"
    case "$_perm" in
        *[4-7]) return 0 ;;
        *) return 1 ;;
    esac
}
